pub fn evaluate(board: &crate::board::Board) -> i32 {
    let mut score = 0i32;
    for r in 0..10usize {
        for c in 0..9usize {
            let p = board.cells[r][c];
            if p.is_empty() {
                continue;
            }
            let val = BASE_VALUES[p.piece_type as usize] + pst_value(p.piece_type, p.side, r, c);
            if p.side == Side::Red {
                score += val;
            } else {
                score -= val;
            }
        }
    }
    score
}

pub fn eval_for_side(board: &crate::board::Board, side: Side) -> i32 {
    let raw = evaluate(board);
    if side == Side::Red { raw } else { -raw }
}

fn pst_value(pt: PieceType, side: Side, r: usize, c: usize) -> i32 {
    match pt {
        PieceType::King => 0,
        PieceType::Advisor => {
            match side {
                Side::Red => RED_ADVISOR_PST[r][c],
                Side::Black => BLACK_ADVISOR_PST[r][c],
                _ => 0,
            }
        }
        PieceType::Elephant => {
            match side {
                Side::Red => RED_ELEPHANT_PST[r][c],
                Side::Black => BLACK_ELEPHANT_PST[r][c],
                _ => 0,
            }
        }
        PieceType::Horse => {
            match side {
                Side::Red => RED_HORSE_PST[r][c],
                Side::Black => BLACK_HORSE_PST[r][c],
                _ => 0,
            }
        }
        PieceType::Chariot => {
            match side {
                Side::Red => RED_CHARIOT_PST[r][c],
                Side::Black => BLACK_CHARIOT_PST[r][c],
                _ => 0,
            }
        }
        PieceType::Cannon => {
            match side {
                Side::Red => RED_CANNON_PST[r][c],
                Side::Black => BLACK_CANNON_PST[r][c],
                _ => 0,
            }
        }
        PieceType::Pawn => {
            match side {
                Side::Red => RED_PAWN_PST[r][c],
                Side::Black => BLACK_PAWN_PST[r][c],
                _ => 0,
            }
        }
        _ => 0,
    }
}
